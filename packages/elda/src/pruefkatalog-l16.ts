function arten(spanne: string): number[] {
  if (spanne === '') return [];
  return spanne.split(',').flatMap((teil) => {
    const [von, bis] = teil.split('-').map(Number);
    if (bis === undefined) return [von!];
    return Array.from({ length: bis - von! + 1 }, (_, i) => von! + i);
  });
}

